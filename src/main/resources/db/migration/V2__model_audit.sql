-- =============================================================================
-- V2 · 模型调用审计与置信度样本
-- =============================================================================
--  同一份脚本跑在 PostgreSQL（生产）与 H2 PG 兼容模式（测试）上，**不允许分叉**；
--  兼容性约束与 V1 相同（不用 PG 专有类型 / H2 专有语法 / AUTO_INCREMENT）。
--
--  为什么时间列存 BIGINT 毫秒而不是 TIMESTAMP：
--    T28 的主用例是「导出某一天」。按自然日切区间就绕不开时区，而院内三件事会互相打架：
--    服务器 TZ 被运维改过一次、跨夏令时的那一天、测试里固定时钟。
--    at_ms 是绝对时刻，与 TZ 无关；「某一天」这一刀由应用层按 --tz 切，
--    同一个区间在两次查询里必然一致。V1 的 message_ledger.at 是业务发生时间、
--    需要按本地时间肉眼读，保留 TIMESTAMP 是对的，两者不冲突。
--
--  为什么 summary 只落 VARCHAR(1024)：
--    入参摘要的形态本身是「字段名(len=n) + 8 位摘要」，正常在 200 字符内；
--    超过 1KB 意味着装配时把原文塞进了摘要，那是要在导出层挡掉的错误形状，
--    不是要放宽的容量。
-- =============================================================================

-- model_call_audit：一行 = 一次模型调用尝试（重试序列的每次尝试各占一行）
CREATE TABLE model_call_audit (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 绝对时刻（epoch 毫秒），见文件头「为什么存 BIGINT 毫秒」
    at_ms                   BIGINT       NOT NULL,

    -- 模型名与操作名：出问题时的第一手定位信息（哪个模型、做的哪一步）
    model                   VARCHAR(128) NOT NULL,
    operation               VARCHAR(64)  NOT NULL,

    -- 单次尝试耗时（含退避等待以外的网络与推理时间）
    elapsed_ms              BIGINT       NOT NULL,

    -- token 用量：端点没返回 usage 段时记 0，不编数
    prompt_tokens           INTEGER      NOT NULL DEFAULT 0,
    completion_tokens       INTEGER      NOT NULL DEFAULT 0,

    -- 端点返回的请求标识；未返回时记 '(未返回)'
    request_id              VARCHAR(128) NOT NULL,

    -- 是否走了降级路径。降级行必有 error_code（应用层 ModelCallRecord 的不变量）
    degraded                BOOLEAN      NOT NULL,
    error_code              VARCHAR(64),

    -- 入参摘要：字段名 + 长度 + 8 位摘要，**不含原文**；
    -- 导出时还要过一遍 AuditTextGuard（非 ASCII 一律替换成 *）
    input_summary           VARCHAR(1024) NOT NULL DEFAULT ''
);

-- 主查询面：「某一天的全部调用」与「某一天某个操作的调用」
CREATE INDEX idx_model_audit_at        ON model_call_audit (at_ms);
CREATE INDEX idx_model_audit_at_op     ON model_call_audit (at_ms, operation);

-- confidence_sample：一行 = 一个置信度观察点（一条报文可能贡献 0 到 N 个观察点）
--
-- 为什么不按报文建表而是按观察点存：Z 段一条报文能贡献 N 个字段映射置信度，
-- 身份候选一条报文能贡献 N 条候选 + 1 条「没给结论」。存观察点才能把
-- 「各桶条数」算准；报文数由 subject_ref 去重得出，两者口径不同、不能互相顶替。
CREATE TABLE confidence_sample (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 绝对时刻（epoch 毫秒），与 model_call_audit 同一口径
    at_ms                   BIGINT       NOT NULL,

    -- 观察点所属序列：'Z_ALIGNMENT'（Z 段映射）/ 'IDENTITY_CANDIDATE'（身份候选）
    series                  VARCHAR(32)  NOT NULL,

    -- 报文级引用（MSH-10 控制号；取不到时留空串）。
    -- 只用于去重算「涉及多少条报文」，不进 CSV 明细列。
    subject_ref             VARCHAR(64)  NOT NULL DEFAULT '',

    -- 模型给出的置信度；模型没给时记 -1（ZAlignmentReport.Unresolved.NO_CONFIDENCE 同口径），
    -- 由应用层归入 UNKNOWN 桶，**不**在库里拿 0 顶替 —— 0 是一条真实存在的低置信结论
    confidence              DOUBLE PRECISION NOT NULL,

    -- 该观察点是否来自降级路径（模型不可达）
    degraded                BOOLEAN      NOT NULL
);

CREATE INDEX idx_confidence_sample_at_series ON confidence_sample (at_ms, series);

