-- V4 · 确认被拒留痕 confirm_refusal（「不得静默成功」的落点）
--
--  为什么单独一张表而不是塞进 message_audit：
--    message_audit 是**状态迁移**的逐条留痕，且 LedgerAuditChain 的第 5 条不变量
--    锁死了「审计行数 == message_ledger.version」。而确认被拒（重复确认已落地、
--    确认一条已拒收的、两个信息员同时点确认）**没有发生任何状态迁移**，
--    version 不会变。若把它当迁移写进 message_audit，审计链当场断在第 5 条不变量上，
--    而排障的人看到的会是一句「审计链坏了」——把一个正常的业务拒绝报成数据损坏，
--    比不记更糟。因此另立一张只增不改的拒绝表，与 message_audit 并列而不混用。
--
--  这张表回答的是现场真会被问到的一句话：
--  「上午这条为什么一直没落地？是没人点，还是点了没生效？」
--  前者 message_audit 里查不到任何行，后者在本表里能查到
--  「谁、几点、对哪条、当时是什么态、为什么被拒」。
--
--  兼容性：与 V1 同约束——只用 SQL 标准类型与 GENERATED BY DEFAULT AS IDENTITY，
--  PostgreSQL 与 H2 PG 兼容模式执行同一份脚本，不分叉。
-- =============================================================================

CREATE TABLE confirm_refusal (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 关联 message_ledger.id；不建外键约束（与 message_audit 同口径，便于整库清理）。
    ledger_id                   BIGINT       NOT NULL,

    -- 点击确认那一刻这一行的实际状态。拒绝理由离不开它：
    -- 「已落地重复确认」与「拒收条目被确认」是两种现场问题，处置动作不一样。
    actual_state                VARCHAR(32)  NOT NULL,

    -- 操作人：来自 HTTP token 的 subject（T38 校验后传入）。空串会被
    -- ConfirmGate 在入口就拒掉——「谁点的」查不到的行等于没记。
    operator                    VARCHAR(64)  NOT NULL,

    -- 拒绝原因码：ConfirmGate.Refusal 的枚举名，机器可筛。
    -- 「operator-007 连续拒了 30 条」这类判断要靠它聚合，不能靠 detail 自由文本。
    reason                      VARCHAR(64)  NOT NULL,

    -- 人可读的一句话说明。**禁止**在此写入姓名 / 证件号 / 手机号明文：
    -- 这张表是运维会直接 SELECT 出来看的。
    detail                      VARCHAR(512) NOT NULL DEFAULT '',

    at                          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 「这一条被拒过几次」：同一条报文被反复点确认时，第一条索引就能给出全部尝试。
CREATE INDEX idx_confirm_refusal_ledger_at ON confirm_refusal (ledger_id, at);

-- 「今天上午是谁在反复点确认」：按原因码聚合拒绝来源，不走全表扫描。
CREATE INDEX idx_confirm_refusal_reason_at ON confirm_refusal (reason, at);

