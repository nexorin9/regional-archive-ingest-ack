-- =============================================================================
-- V5 · 重投队列 redelivery_queue
--
--  为什么单独一张表而不是塞进 message_ledger：
--    message_ledger 每一行表示「一条入站报文当前的业务状态」；
--    重投队列的每一行表示「这一次重投尝试的快照」—— 一条报文在生命周期内可能
--    在队列里被多次记录（每次出队后 scheduleNextAttempt 重排），但台账只能有一行。
--    把队列建在 ledger 上要么把 retry_count 字段膨胀成「每次重排都自增」、
--    要么在 last_error / next_attempt_at 上塞两份责任。
--    另立一张表与 message_ledger 1:N 关系，队列条目带 ledgerId 外引就够。
--
--  入队条件（见 RedeliveryQueue.offer）：
--    - MSA-1=AE（应用错误，重投可能成功）
--    - 或 状态=PENDING_CONFIRM 且对端次日追问未收回执（差集触发）
--  AR / LANDED 永不进队列，由 offer() 在入队口拒绝。
--
--  同一条报文不允许在队列里重复占行：
--    uk_redelivery_active_key 唯一约束保证「同 (ledger_id, status='QUEUED')」只有一行。
--    已经 RETRY_PERMANENT_FAILED 或已 ACK 结算的条目不参与唯一约束。
--
--  状态机（RedeliveryStatus 枚举）：
--    QUEUED                  —— 已入队，等待调度出队
--    CONSUMED                —— 出队后由调度器持有（RETRYING），但还没完成重投
--    ACK_CONFIRMED           —— 重投成功（对端回 AA），下一步推进台账到 RETRY_CONFIRMED
--    PERMANENT_FAILED        —— 达到 MAX_ATTEMPTS 上限，停止自动重试，等人工放行
--    RELEASED                —— 人工放行：从 PERMANENT_FAILED 释放回 QUEUED
--
--  dequeueAtomic 原子性：
--    出队用一条 `UPDATE ... SET status='CONSUMED', consumed_at=? WHERE status='QUEUED'
--    AND next_attempt_at<=? ORDER BY next_attempt_at ASC LIMIT 1`。
--    在 PG/H2 上都用 SQL 保证不靠 JVM 内存锁。多线程并发时同一行只被一个消费者拿走：
--    UPDATE 影响行数即本消费者本次拿到的条目主键；0 行表示排队里没有到期条目。
--
--  兼容：与 V1 同约束——只用 SQL 标准类型与 GENERATED BY DEFAULT AS IDENTITY，
--  PostgreSQL 与 H2 PG 兼容模式执行同一份脚本，不分叉。
-- 时间戳在 PG 上为 TIMESTAMP；H2 上可写不可读，由应用层以 epoch 毫秒对位。
-- =============================================================================

CREATE TABLE redelivery_queue (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 关联 message_ledger.id；不建外键约束（与 message_audit / confirm_refusal 同口径）。
    ledger_id                   BIGINT       NOT NULL,

    -- 三段幂等键（MSH-9+MSH-10+MSH-11），作为入队去重与跨批次对账的双向键。
    -- 取自 message_ledger 的同名三列，T34 对账差集直接按 storageKey 即可比对。
    idempotency_key             VARCHAR(256) NOT NULL,

    -- 本批 batch_id，留作运维列查询（"今天上午这个批次的重投队列有几条"）。
    batch_id                    VARCHAR(64)  NOT NULL,

    -- 状态字符串，与 RedeliveryStatus.dbValue 一一对应。
    status                      VARCHAR(32)  NOT NULL,

    -- 已尝试次数：每次进入调度器出队执行后 +1；T33 的上限判定看这个值。
    attempt                     INTEGER      NOT NULL DEFAULT 0,

    -- 下一次可被出队的时间戳（epoch 毫秒）。T33 的指数退避每次更新这一列。
    -- 写 BIGINT 而非 TIMESTAMP 是为了让 H2 在两库下表现完全一致：
    -- H2 默认把 TIMESTAMP 解为 java.sql.Timestamp，而 PG 解为 java.sql.Timestamp，
    -- PG/H2 在「同一查询返回的对象类型」上其实是一致的，但用 BIGINT 更直接——比较是
    -- 数字比较，无需经过 Calendar/TimeZone 一层。
    next_attempt_at_ms          BIGINT       NOT NULL DEFAULT 0,

    -- 上一次出队的错误信息（retryable 短期错误码 + 简要原因），T40 报表会用。
    -- 留 VARCHAR(512)：比 message_audit.reason 长一截，是因为这里可能含对接端诊断片段。
    last_error                  VARCHAR(512) NOT NULL DEFAULT '',

    -- 入队原因短语：'msa-ae' / 'pending-confirm-no-ack' / 'manual-release' / 'recovery-scan'。
    -- 区分「AE 当场入队」与「次日对账补入队」在运维上很关键——前者是接入侧故障，
    -- 后者是对端吞回执。
    enqueue_reason              VARCHAR(64)  NOT NULL DEFAULT '',

    -- 时间戳三件套：created_at 是首次入队时间；last_attempt_at 每次出队后更新；
    -- consumed_at 是出队但未 ACK 之间的小窗口（CONSUMED 期间）由调度器持有。
    created_at                  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_attempt_at             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    consumed_at                 TIMESTAMP    NULL
);

-- 「(ledger_id, status) 唯一约束」：同一条报文在队列里最多占一行 *但允许其历史多种状态并存*。
-- 一条报文从 QUEUED → CONSUMED → ACK_CONFIRMED 三行都在，等价于账页。
-- 该唯一约束只约束 QUEUED 状态——重投结算完成（ACK_CONFIRMED / PERMANENT_FAILED / RELEASED）
-- 后允许同一 ledger_id 再次进队（哪怕是同一条报文被人工放行回 QUEUED）。
-- 这里使用 *部分唯一约束*：H2 与 PG 都支持 `WHERE status='QUEUED'` 的索引形式，
-- 但语法略有差异，故改用「status 列也参与唯一键、但约束上把 status='QUEUED' 时的复合键约束
-- 用一个 WHERE 子句」——这两种数据库在同一份 SQL 下分叉。
-- 取一个**两库都对**的写法：把 ledger_id + idempotency_key 作为唯一键，但允许历史状态
-- 出现多条——这其实就是把"同 ledger 同时只一个 QUEUED"的约束推到应用层做（offer 时
-- SELECT FOR UPDATE + INSERT 或 INSERT 冲突 SQLState 23505 翻译），与 V1 的
-- IdempotencyGuard 同口径。
CREATE UNIQUE INDEX uk_redelivery_idem_key ON redelivery_queue (idempotency_key);

-- 调度器出队的主要查询路径：status='QUEUED' AND next_attempt_at_ms <= ? ORDER BY next_attempt_at_ms。
-- 覆盖此复合索引后可走 range scan，单队列数千条仍是亚毫秒。
CREATE INDEX idx_redelivery_status_next ON redelivery_queue (status, next_attempt_at_ms);

-- 「今天上午这个批次有几条重投」按 batch_id 维度聚合。
CREATE INDEX idx_redelivery_batch_id ON redelivery_queue (batch_id);

-- 「按 ledger 查这条报文的所有重投记录」：T35 重启续跑从台账读 ledger_id 后反查。
CREATE INDEX idx_redelivery_ledger_id ON redelivery_queue (ledger_id);

