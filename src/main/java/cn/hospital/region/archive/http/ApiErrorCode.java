package cn.hospital.region.archive.http;

/**
 * 本院 HTTP API 的<b>错误码目录</b> —— 每一类失败有且只有一个机器码，且状态码由码决定。
 *
 * <h2>为什么逐条枚举而不是随手写状态码</h2>
 * <p>确认动作由<b>院内既有系统</b>调用，那边要写的不是「如果失败就弹个窗」，而是
 * 「拿到 409 就把这条从待办列表里去掉、拿到 401 就跳登录页」。这两种处理完全相反，
 * 而 {@code 409} 与 {@code 400} 在很多框架的默认分支里长得一样（都归「请求有问题」）。
 * 把「状态码 + 机器码」绑成一个枚举，那边就只剩一张 switch，且漏网的新错误会被
 * 类加载期的不变量挡下来。
 *
 * <h2>五档状态码各回答一个现场问题</h2>
 * <ul>
 *   <li><b>400</b>：请求本身不合法（缺字段、JSON 坏了、状态名拼错）——<b>改请求</b>，重发有意义；</li>
 *   <li><b>401</b>：没带令牌或令牌不对——<b>改凭据</b>，重发有意义；</li>
 *   <li><b>404</b>：令牌对了，但那条报文不在这批里——<b>换批次号</b>，重发没意义；</li>
 *   <li><b>409</b>：令牌对了、条目也在，但<b>当前状态不允许这一步</b>——重发<b>永远</b>没意义，
 *       必须由人决定是撤回重来还是就留着。这是本产品最容易被写成 200 或 500 的一档，
 *       而它恰好是最该让人看见的一档：两个信息员同时点同一条，就该在这里撞见；</li>
 *   <li><b>502 / 503</b>：本端正常，是<b>对端</b>回执接口不可用——本产品自己没坏，
 *       不该让院内系统以为要回滚或重试整个批次；</li>
 *   <li><b>500</b>：本端内部错误——响应体<b>不带异常堆栈</b>，只带一句「已记录」，
 *       细节只进本机日志（T40 扫明文）。</li>
 * </ul>
 */
public enum ApiErrorCode {

    // ---- 400：请求不合法 ----

    /** 请求体不是合法 JSON。 */
    MALFORMED_JSON("请求体不是合法的 JSON", 400),

    /** 必填字段缺失或为空，{@code message} 里点名缺哪个字段。 */
    MISSING_FIELD("请求缺少必填字段", 400),

    /** 查询参数取值非法（如 {@code state=RECEVIED} 拼错、{@code limit} 非数字）。 */
    INVALID_PARAMETER("请求参数取值非法", 400),

    /** 方法不对（同一个路径上发了 GET 之外的动词）。 */
    METHOD_NOT_ALLOWED("该路径不接受这个 HTTP 方法", 405),

    // ---- 401：凭据 ----

    /** 完全没有带令牌。 */
    TOKEN_MISSING("缺少接入令牌", 401),

    /** 带了令牌但对不上。 */
    TOKEN_INVALID("接入令牌无效", 401),

    // ---- 404 / 409 ----

    /** 路径不在这份契约里。 */
    ROUTE_NOT_FOUND("没有这个接口", 404),

    /** 台账里没有这一行，或这一行不属于这个批次。 */
    LEDGER_ROW_NOT_FOUND("台账里没有这一条，或不属于这个批次", 404),

    /** 拒绝类冲突：已落地重复确认、拒收条目被确认、并发争用、状态迁移非法。 */
    STATE_CONFLICT("当前状态不允许这一步操作", 409),

    // ---- 对端不可用（502/503）：本端没坏 ----

    /** 区域平台回执查询接口返回了非 2xx。 */
    REMOTE_REJECTED("区域平台回执接口拒绝了本次查询", 502),

    /** 区域平台回执查询接口连不上或超时——本端状态不受影响，稍后重试即可。 */
    REMOTE_UNAVAILABLE("区域平台回执接口暂时不可达", 503),

    /**
     * 确认动作已过四道闸，但<b>写院内患者主索引失败</b>（HIS 不可达或拒绝）。
     *
     * <p>走 503 而不是 409：本条<b>仍然停在待确认</b>，报文原文与幂等键都还在台账里，
     * 人重试一次即可落地 —— 这不是「状态冲突」，是下游临时不可用。若报 409，
     * 调用方按惯例会把这条从待办里去掉，于是它会永远没人再点。
     */
    HIS_WRITE_FAILED("院内患者主索引写入失败，该条仍停在待确认，可重试", 503),

    // ---- 500 ----

    /** 本端内部错误（数据库不可用等）；细节只进本机日志。 */
    INTERNAL_ERROR("服务端内部错误，已记录到本机日志", 500);

    private final String zhSummary;
    private final int httpStatus;

    ApiErrorCode(String zhSummary, int httpStatus) {
        this.zhSummary = zhSummary;
        this.httpStatus = httpStatus;
    }

    /** 响应体 {@code message} 字段的兜底中文说明（可被更具体的说明覆盖）。 */
    public String zhSummary() {
        return zhSummary;
    }

    /** 状态码由码决定：调用点不自己写 {@code 200/409}，只挑码。 */
    public int httpStatus() {
        return httpStatus;
    }
}